-- Trigger to auto-update updated_at for rider_status
CREATE OR REPLACE FUNCTION update_rider_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_update_rider_timestamp ON public.rider_status;
CREATE TRIGGER tr_update_rider_timestamp
    BEFORE UPDATE ON public.rider_status
    FOR EACH ROW EXECUTE PROCEDURE update_rider_timestamp();

