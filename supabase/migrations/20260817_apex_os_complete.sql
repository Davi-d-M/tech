-- 8. TACTICAL STATE MACHINE FUNCTIONS

-- Enforce valid transitions
CREATE OR REPLACE FUNCTION public.check_order_transition()
RETURNS trigger AS $$
BEGIN
    -- Delivered cannot go back to Processing
    IF OLD.status = 'Delivered' AND NEW.status = 'Processing' THEN
        RAISE EXCEPTION 'Apex OS Protocol Violation: Cannot revert delivered mission to processing.';
    END IF;

    -- Update order cost and profit triggers here...

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_order_state_machine ON public.orders;
CREATE TRIGGER tr_order_state_machine
    BEFORE UPDATE ON public.orders
    FOR EACH ROW EXECUTE PROCEDURE public.check_order_transition();

-- 9. CONTRIBUTION PROFIT AUTOMATION
CREATE OR REPLACE FUNCTION public.calculate_contribution_profit()
RETURNS trigger AS $$
BEGIN
    IF NEW.status = 'Paid' AND OLD.status != 'Paid' THEN
        -- Automated Ledger Entries
        -- 1. Revenue
        INSERT INTO public.financial_ledger (order_id, entry_type, amount, description)
        VALUES (NEW.id, 'REVENUE', NEW.total_price, 'Customer Payment Received');

        -- 2. Fees (Estimated 3% for Paystack)
        INSERT INTO public.financial_ledger (order_id, entry_type, amount, description)
        VALUES (NEW.id, 'PAYMENT_FEE', -(NEW.total_price * 0.03), 'Payment Gateway Charge');
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_contribution_profit ON public.orders;
CREATE TRIGGER tr_contribution_profit
    AFTER UPDATE ON public.orders
    FOR EACH ROW EXECUTE PROCEDURE public.calculate_contribution_profit();
