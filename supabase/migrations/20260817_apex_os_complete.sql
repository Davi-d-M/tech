-- 4. ORDER ITEMS (The Granular Truth)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id),
    inventory_unit_id BIGINT REFERENCES inventory_units(id), -- Specific IMEI linked here
    quantity INTEGER DEFAULT 1,
    unit_price NUMERIC NOT NULL,
    unit_cost NUMERIC NOT NULL,
    supplier_id BIGINT REFERENCES suppliers(id),
    status TEXT DEFAULT 'Pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 5. THE LEDGER (Financial Fortress)
CREATE TABLE IF NOT EXISTS public.financial_ledger (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    entry_type TEXT NOT NULL, -- REVENUE, SUPPLIER_PAYABLE, DELIVERY_FEE, PAYMENT_FEE, REFUND
    amount NUMERIC NOT NULL,
    description TEXT,
    is_reconciled BOOLEAN DEFAULT false,
    reconciliation_ref TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 6. EXCEPTION CENTER (Red Circle Hub)
CREATE TABLE IF NOT EXISTS public.exception_center (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    exception_code TEXT NOT NULL, -- PM_01 (Payment Mismatch), LD_01 (Logistics Delay), etc.
    type TEXT NOT NULL, -- FINANCE, LOGISTICS, INVENTORY, RISK
    severity TEXT DEFAULT 'Warning',
    title TEXT NOT NULL,
    description TEXT,
    order_id BIGINT REFERENCES public.orders(id),
    status TEXT DEFAULT 'Open', -- Open, InProgress, Resolved
    owner_role TEXT, -- Which admin role should fix this
    deadline TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    resolved_at TIMESTAMP WITH TIME ZONE
);

