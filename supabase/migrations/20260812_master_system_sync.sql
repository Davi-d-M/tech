-- 12. TACTICAL FUNCTIONS (RPCs)

-- Credit Rider Wallet securely
CREATE OR REPLACE FUNCTION public.credit_rider_wallet(phone_input TEXT, amount_input NUMERIC)
RETURNS VOID AS $$
BEGIN
    INSERT INTO public.rider_wallets (rider_phone, balance, total_earned)
    VALUES (phone_input, amount_input, amount_input)
    ON CONFLICT (rider_phone)
    DO UPDATE SET
        balance = public.rider_wallets.balance + amount_input,
        total_earned = public.rider_wallets.total_earned + amount_input,
        updated_at = NOW();
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Get User ID by Email (For Staff Auth)
CREATE OR REPLACE FUNCTION public.get_user_id_by_email(email_input TEXT)
RETURNS TABLE (id UUID) AS $$
BEGIN
    RETURN QUERY SELECT p.id FROM public.profiles p WHERE p.email = email_input;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 13. AUTH TRIGGER (Automated Profile Creation)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, phone_number)
  VA
  LUES (
    new.id,
    new.email,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'phone_number'
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger execution
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 14. REFERRAL TRACKING RPC
CREATE OR REPLACE FUNCTION public.increment_referral_clicks(code_input TEXT)
RETURNS VOID AS $$
BEGIN
    UPDATE public.profiles
    SET referral_clicks = referral_clicks + 1
    WHERE referral_code = code_input;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
